create table if not exists public.game_odds_snapshots (
  id bigint generated by default as identity primary key,
  game_id uuid not null references public.games(id) on delete cascade,
  sport text not null check (sport in ('nfl', 'ncaaf')),
  sportsbook text not null,
  market text not null check (market in ('spreads', 'totals', 'h2h')),
  observed_at timestamptz not null default now(),
  provider_updated_at timestamptz,
  outcomes jsonb not null default '[]'::jsonb check (jsonb_typeof(outcomes) = 'array'),
  odds_fingerprint text generated always as (md5(outcomes::text || '|' || coalesce(provider_updated_at::text, ''))) stored,
  unique (game_id, sportsbook, market, odds_fingerprint)
);

create index if not exists game_odds_snapshots_game_market_observed_idx
  on public.game_odds_snapshots (game_id, market, observed_at desc);

create index if not exists game_odds_snapshots_sport_observed_idx
  on public.game_odds_snapshots (sport, observed_at desc);

alter table public.game_odds_snapshots enable row level security;
revoke all on table public.game_odds_snapshots from anon, authenticated;
grant select, insert on table public.game_odds_snapshots to service_role;
grant usage, select on sequence public.game_odds_snapshots_id_seq to service_role;

create or replace view public.game_odds_snapshot_edges
with (security_invoker = true)
as
with ranked as (
  select
    snapshot.id,
    snapshot.game_id,
    snapshot.sport,
    snapshot.sportsbook,
    snapshot.market,
    snapshot.observed_at,
    snapshot.provider_updated_at,
    snapshot.outcomes,
    row_number() over (
      partition by snapshot.game_id, snapshot.market, snapshot.sportsbook
      order by snapshot.observed_at asc, snapshot.id asc
    ) as first_observation,
    row_number() over (
      partition by snapshot.game_id, snapshot.market, snapshot.sportsbook
      order by snapshot.observed_at desc, snapshot.id desc
    ) as last_observation,
    count(*) over (
      partition by snapshot.game_id, snapshot.market, snapshot.sportsbook
    ) as observation_count
  from public.game_odds_snapshots as snapshot
  join public.games as game on game.id = snapshot.game_id
  where snapshot.observed_at <= game.starts_at
)
select id, game_id, sport, sportsbook, market, observed_at, provider_updated_at, outcomes,
  (first_observation = 1) as is_earliest, observation_count
from ranked
where first_observation = 1
union all
select id, game_id, sport, sportsbook, market, observed_at, provider_updated_at, outcomes,
  (first_observation = 1) as is_earliest, observation_count
from ranked
where last_observation = 1 and observation_count > 1;

revoke all on table public.game_odds_snapshot_edges from anon, authenticated;
grant select on table public.game_odds_snapshot_edges to service_role;

